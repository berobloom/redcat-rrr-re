#!/usr/bin/env python3
"""vault.py: write the project's documentation and lessons learned as an Obsidian vault.

usage: vault.py [OUTDIR]      (default ~/Documents/Knowledge/<project>)

The repo is the record and git its history; the vault is generated from it, so never edit a
generated note: rerun this instead. SOURCES below says which file becomes which notes:
  sections  one note per `## ` section            lessons  one note per bold-led list entry
  items     one note per numbered question / hypothesis bullet (QUESTIONS.md)
Lessons go to Lessons/<kind>/ (gotchas, levers, probe traps, dead ends, working with agents).
Home.md holds what the project is, where it stands, Dataview views and an index of every note.

Every note has frontmatter `confidence` (CONFIRMED, STRONGLY SUPPORTED, LIKELY, SPECULATIVE,
RETRACTED, open, resolved, or unrated when the source states none), `origin` (the project whose
work it records) and `source`, and matching tags. Only notes carrying the generated marker are
ever overwritten or removed; anything else in OUTDIR (your own notes, .obsidian/) is left alone.
The engine below the configuration is the same in redcat-rrr-re, wacky-re, sam-re, batterycheck-re.
"""

# ---------------------------------------------------------------- this repo
PROJECT = 'redcat-rrr-re'
TITLE = "RedCat's Razende Rekenrace"
INDEX = None
SKIP_FILES = set()
# (repo file or glob, vault folder, unit, confidence rule, origin)
SOURCES = [
    ('research/discoveries.md', 'Discoveries', 'sections', 'CONFIRMED', PROJECT),
    ('research/hypotheses.md', 'Hypotheses', 'sections', 'weakest', PROJECT),
    ('research/open-questions.md', 'Open questions', 'sections', 'questions', PROJECT),
    ('reverse-engineering/architecture.md', 'Architecture', 'sections', 'stated', PROJECT),
    ('reverse-engineering/executables.md', 'Architecture', 'sections', 'stated', PROJECT),
    ('reverse-engineering/file-formats.md', 'Formats', 'sections', 'stated', PROJECT),
    ('reverse-engineering/runtime-dosbox.md', 'Tooling', 'sections', 'stated', PROJECT),
    ('reverse-engineering/watcom.md', 'Tooling', 'sections', 'stated', PROJECT),
    ('MATCHING.md', 'Tooling', 'sections', 'stated', PROJECT),
    ('AGENTS.md', 'Tooling', 'sections', 'stated', PROJECT),
    ('GOTCHAS.md', 'Lessons', 'lessons', 'evidence', PROJECT),
    ('reverse-engineering/watcom-levers.md', 'Lessons', 'lessons', 'wacky-re', 'wacky-re'),
]






# ---------------------------------------------------------------- the engine (same in every repo)
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = subprocess.run(['git', '-C', HERE, 'rev-parse', '--show-toplevel'],
                      capture_output=True, text=True).stdout.strip() or os.path.dirname(HERE)
SCRIPT = os.path.relpath(os.path.abspath(__file__), ROOT)
DEFAULT_OUT = os.path.expanduser('~/Documents/Knowledge/' + PROJECT)
MARK = '> Generated by `%s` from the repo. Do not edit: changes are overwritten.' % SCRIPT
LEVELS = ['CONFIRMED', 'STRONGLY SUPPORTED', 'LIKELY', 'SPECULATIVE', 'RETRACTED']
LEVEL_RE = re.compile(r'\b(CONFIRMED|STRONGLY SUPPORTED|LIKELY|SPECULATIVE|RETRACTED|RESOLVED)\b')
DONE_RE = re.compile(r'^\W*(RESOLVED|ANSWERED|CLOSED|SETTLED|DONE)\b')
KINDS = [('lever', 'Levers'), ('dead-end', 'Dead ends'), ('probe-trap', 'Probe traps'), ('gotcha', 'Gotchas'),
         ('working-with-agents', 'Working with agents')]


def read(p):
    return open(os.path.join(ROOT, p), encoding='utf-8').read()


def expand(sources):
    """SOURCES with globs ('findings/*.md') expanded, files that do not exist dropped"""
    import glob
    out = []
    for s in sources:
        for p in sorted(glob.glob(os.path.join(ROOT, s[0]))):
            rel = os.path.relpath(p, ROOT)
            if os.path.basename(rel) in SKIP_FILES:
                continue
            folder = s[1].replace('{stem}', os.path.splitext(os.path.basename(rel))[0].replace('_', ' '))
            out.append((rel, folder) + tuple(s[2:]))
    return out


def slug(title):
    s = title.replace('||', 'or').replace('->', 'to').replace('/', '-').replace('*', '').replace('`', '')
    s = re.sub(r'[\\:?"<>|#^\[\]]', '', s)
    return re.sub(r'\s+', ' ', s)[:90].strip(' ,.-')


def short(title, limit=80):
    title = re.sub(r'\s+', ' ', title).strip(' .:')
    if len(title) <= limit:
        return title
    cut = re.split(r'(?<=.{25})(?: \(|: | - |; |, |\. )', title, maxsplit=1)[0]
    return cut if len(cut) <= limit else title[:limit - 3].rsplit(' ', 1)[0] + '...'


def split_sections(text):
    """[(heading, body)] for each `## ` heading"""
    parts = re.split(r'^## (.+)$', text, flags=re.M)
    return [(parts[i].strip(), parts[i + 1].strip('\n')) for i in range(1, len(parts), 2)]


def entries(text):
    """[(heading, entry)]: top-level '- ' and '1. ' list entries with their continuation lines,
    each with the nearest heading above it"""
    out, cur, head = [], None, ''
    for l in text.split('\n'):
        h = re.match(r'#{2,4} (.+)', l)
        if h:
            head, cur = h.group(1).strip(), None
        elif re.match(r'(- |\d+\. )', l):
            cur = [re.sub(r'^(- |\d+\. )', '', l)]
            out.append((head + ('\0numbered' if l[0].isdigit() else ''), cur))
        elif cur is not None and (l.startswith('  ') or not l.strip()):
            cur.append(l.strip())
        else:
            cur = None
    return [(h, re.sub(r'\n{2,}', '\n\n', '\n'.join(c)).strip()) for h, c in out]


def numbered(head):
    """(heading, True when the entry was a numbered one)"""
    return head.split('\0')[0], head.endswith('\0numbered')


def item_title(body):
    """a question's or hypothesis's own words: its status mark, '(where)' and level dropped"""
    lead = body
    m = re.match(r'\*\*([^*]{0,60})\*\*', lead)
    if m and re.match(r'[A-Z]{3,}', m.group(1)):
        lead = lead[m.end():]
    lead = re.sub(r'^\s*[A-Z]{3,}(?: [A-Z]{2,})*', '', lead)
    lead = re.sub(r'^\s*(?:iter \S+|\d{4}-\d\d-\d\d)', '', lead)
    lead = lead.lstrip()
    if lead.startswith('('):
        depth = 0
        for i, c in enumerate(lead):
            depth += {'(': 1, ')': -1}.get(c, 0)
            if depth == 0:
                lead = lead[i + 1:]
                break
    lead = re.sub(r'^[\s:,-]+', '', lead)
    b = re.match(r'\*\*(.+?)\*\*', lead, re.S)
    t = b.group(1) if b else re.split(r'(?<=[.?!:])\s', lead, 1)[0]
    return short(re.sub(r'\*\*|`', '', t)) or short(body)


def kind_of(heading):
    h = heading.lower()
    for word, kind in (('lever', 'lever'), ('dead end', 'dead-end'), ('probe', 'probe-trap'),
                       ('working with agents', 'working-with-agents')):
        if word in h:
            return kind
    return 'gotcha'


def levels_in(text):
    return [m for m in LEVEL_RE.findall(text) if m != 'RESOLVED']


def weakest(levels):
    """the weakest level claimed; RETRACTED only when nothing else is (a retracted side remark does
    not retract the note)"""
    live = [l for l in levels if l != 'RETRACTED'] or levels
    return max(live, key=LEVELS.index) if live else None


def yaml(d):
    r = ['---']
    for k, v in d.items():
        if isinstance(v, list):
            r.append('%s: [%s]' % (k, ', '.join('"%s"' % x for x in v)))
        elif isinstance(v, str):
            r.append('%s: "%s"' % (k, v.replace('\\', '\\\\').replace('"', '\\"')))
        else:
            r.append('%s: %s' % (k, v))
    return '\n'.join(r + ['---', ''])


def tag(s):
    return re.sub(r'[^a-z0-9/-]+', '-', s.lower()).strip('-')


def note(path, title, conf, origin, kind, source, body, basis, extra=None):
    fm = dict(confidence=conf, origin=origin, kind=kind, source=source)
    fm.update(extra or {})
    fm['tags'] = [PROJECT, 'kind/' + tag(kind), 'confidence/' + tag(conf)] + \
                 (['origin/' + origin] if origin != PROJECT else [])
    head = '**Confidence:** %s (%s).' % (conf, basis)
    if origin != PROJECT:
        head += ' **Origin:** %s: a thing to try on this project, not a fact about it.' % origin
    return path, title, fm, '\n'.join([yaml(fm), MARK, '', '# ' + title, '', head, '', body.strip(), '',
                                      '---', 'Source: `%s`' % source, ''])


def build():
    notes, titles = [], set()

    def unique(folder, title, suffix=''):
        base = slug(title) + suffix
        n, t = 2, base
        while (folder + '/' + t).lower() in titles:
            t, n = '%s (%d)' % (base, n), n + 1
        titles.add((folder + '/' + t).lower())
        return '%s/%s' % (folder, t)

    for src, folder, unit, rule, origin in expand(SOURCES):
        text = read(src)
        if unit == 'sections':
            secs = split_sections(text)
            if not secs:   # a file without `## ` headings is one note
                m = re.match(r'# (.+)', text)
                secs = [(m.group(1).strip() if m else os.path.basename(src), re.sub(r'^# .*\n', '', text))]
            for head, body in secs:
                if not body.strip():
                    continue
                lv = levels_in(head + '\n' + body)
                extra = {}
                if rule == 'CONFIRMED':
                    conf, basis = 'CONFIRMED', '`%s` holds confirmed findings only' % src
                elif rule == 'weakest':
                    conf = weakest(lv) or 'SPECULATIVE'
                    basis = 'the weakest level of the claims below' if lv else 'no level stated'
                elif rule == 'questions':
                    items = re.findall(r'^\d+\. (.*)', body, re.M)
                    done = sum(1 for i in items if 'RESOLVED' in i[:40])
                    conf = 'open' if done < len(items) else 'resolved'
                    basis = '%d of %d questions resolved' % (done, len(items))
                    extra = dict(questions=len(items), resolved=done)
                else:
                    stated = levels_in(head)
                    conf = stated[0] if stated else (weakest(lv) or 'unrated')
                    basis = ('stated in the heading' if stated else
                             'the weakest level stated below' if lv else 'the source states no level')
                kind = {'Discoveries': 'discoveries', 'Hypotheses': 'hypotheses',
                        'Open questions': 'open questions'}.get(folder, 'finding' if folder.startswith('Findings')
                                                                else 'documentation')
                notes.append(note(unique(folder, head), head, conf, origin, kind,
                                  '%s § %s' % (src, head), body, basis, extra))
        elif unit == 'items':   # QUESTIONS.md: one note per numbered question / hypothesis bullet
            for head, body in entries(text):
                if re.match(r'<\w', body) or re.search(r'^(?:\*\*)?\w*:? ?<claim>', body) or '<question>' in body:
                    continue   # the template's placeholder
                head, num = numbered(head)
                kind = 'question' if num else 'hypothesis'
                title = item_title(body)
                lv = levels_in(body[:60])
                if DONE_RE.match(re.sub(r'\*', '', body)) or 'RESOLVED' in body[:40]:
                    conf, basis = 'resolved', 'marked resolved in the source'
                elif lv:
                    conf, basis = lv[0], 'level stated in the entry'
                elif kind == 'question':
                    conf, basis = 'open', 'an open question'
                else:
                    conf, basis = 'SPECULATIVE', 'no level stated'
                notes.append(note(unique(folder + ('/Hypotheses' if kind == 'hypothesis' else '/Questions'), title),
                                  title, conf, origin, kind, '%s § %s' % (src, head), body, basis))
        else:   # 'lessons': one note per list entry with a bold lead
            for head, body in entries(text):
                head = numbered(head)[0]
                t = re.match(r'(?:\.\.\. )?\*\*(.+?)\*\*', body, re.S)
                if not t:
                    continue
                title = short(t.group(1))
                kind = kind_of(head)
                lv = levels_in(body)
                if origin != PROJECT:
                    conf, basis = 'LIKELY', 'measured on %s, not on this game' % origin
                elif lv:
                    conf, basis = weakest(lv), 'level stated in the entry'
                elif re.search(r'0x[0-9a-fA-F]{3,}|[0-9A-F]{4}:[0-9A-F]{4}|\d+ ?-> ?\d+|\d+ rows', body):
                    conf, basis = 'CONFIRMED', 'the entry cites an address or a measured row count'
                else:
                    conf, basis = 'LIKELY', 'the entry cites no address or measurement'
                if kind == 'dead-end':
                    basis += '; a dead end: this was tried and did not work'
                path = unique('Lessons/' + dict(KINDS)[kind], title,
                              ' (%s)' % origin if origin != PROJECT else '')
                notes.append(note(path, title, conf, origin, kind, '%s § %s' % (src, head),
                                  body.replace('[generic]', '').strip(), basis,
                                  dict(generic='[generic]' in body, section=head)))
    return notes


def home(notes):
    commit = subprocess.run(['git', '-C', ROOT, 'log', '-1', '--format=%h %ad', '--date=short'],
                            capture_output=True, text=True).stdout.strip()
    readme = read('README.md').split('\n## ')[0]
    readme = re.sub(r'<p>.*?</p>|<img[^>]*>|!\[[^\]]*\]\([^)]*\)', '', readme, flags=re.S)
    readme = re.sub(r'^# .*\n', '', readme)
    progress = re.search(r'^\*\*.*\*\*$', read('PROGRESS.md'), re.M) if os.path.exists(
        os.path.join(ROOT, 'PROGRESS.md')) else None
    state = dict(split_sections(read('STATUS.md'))).get('State', '')
    h = [MARK, '', '# ' + TITLE, '', re.sub(r'\n{3,}', '\n\n', readme).strip(), '',
         'Repo state: `%s`. %s' % (commit, progress.group(0) if progress else ''), '',
         '## Where it stands', '', state.strip(), '']
    if INDEX and os.path.exists(os.path.join(ROOT, INDEX)):
        h += ['## What is known, by question (`%s`)' % INDEX, '',
              re.sub(r'^# .*\n', '', read(INDEX)).strip(), '']
    h += ['## How to read this vault', '',
          '- Every note starts with its `confidence` (CONFIRMED, STRONGLY SUPPORTED, LIKELY, SPECULATIVE; '
          '`open`/`resolved` for questions; `unrated` when the source states no level) and why, and ends '
          'with the repo file it came from. A note made of several claims takes the weakest.',
          '- **Lessons** are what the work taught: gotchas, matching levers that worked, probe traps, '
          'dead ends (tried, failed: do not retry without a new idea), and how to work with agents. '
          'A note with another `origin` was learnt on that project: a thing to try here, not a fact.',
          '- The repo is the record and git its history: regenerate with `%s`; write your own notes '
          'outside the generated folders.' % SCRIPT, '',
          '## Live views (Dataview)', '',
          '```dataview', 'TABLE confidence, origin, section FROM "Lessons" WHERE kind = "dead-end"',
          'SORT origin ASC', '```', '',
          '```dataview', 'TABLE confidence, source FROM #%s WHERE confidence = "open" OR confidence = "LIKELY" '
          'OR confidence = "SPECULATIVE"' % PROJECT, 'SORT confidence ASC', '```', '',
          '```dataview', 'TABLE length(rows) AS notes FROM #%s GROUP BY confidence' % PROJECT, '```', '',
          '## Index', '']
    groups = {}
    for path, title, fm, _ in notes:
        groups.setdefault(path.rsplit('/', 1)[0], []).append((path, title, fm))
    for folder in sorted(groups, key=lambda f: (f.startswith('Lessons'), f)):
        h += ['### %s (%d)' % (folder, len(groups[folder])), '']
        h += ['- [[%s|%s]] · %s%s' % (p, re.sub(r'[\[\]|]', '', t), fm['confidence'],
                                      ' · ' + fm['origin'] if fm['origin'] != PROJECT else '')
              for p, t, fm in groups[folder]]
        h += ['']
    return '\n'.join(h)


def main():
    if len(sys.argv) > 2:
        sys.exit(__doc__)
    out = os.path.abspath(sys.argv[1] if len(sys.argv) == 2 else DEFAULT_OUT)
    notes = build()
    files = {p + '.md': text for p, _, _, text in notes}
    files['Home.md'] = home(notes)
    for d, _, fs in os.walk(out):
        if '.obsidian' in d:
            continue
        for f in fs:
            p = os.path.join(d, f)
            if f.endswith('.md') and os.path.relpath(p, out) not in files and \
                    'Do not edit: changes are overwritten.' in open(p, encoding='utf-8').read():
                os.remove(p)
    for d, _, _ in sorted(os.walk(out), reverse=True):
        if d != out and '.obsidian' not in d and not os.listdir(d):
            os.rmdir(d)
    for rel, text in files.items():
        os.makedirs(os.path.dirname(os.path.join(out, rel)), exist_ok=True)
        open(os.path.join(out, rel), 'w', encoding='utf-8').write(text)
    count = {}
    for _, _, fm, _ in notes:
        count[fm['confidence']] = count.get(fm['confidence'], 0) + 1
    print('%s: %d notes + Home.md (%s)' % (out, len(notes), ', '.join('%s %d' % kv for kv in sorted(count.items()))))


if __name__ == '__main__':
    main()
