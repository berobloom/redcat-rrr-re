#!/usr/bin/env python3
"""vault.py: write the matching decompilation's knowledge as Obsidian notes.

usage: vault.py OUTDIR        (run src/check.sh first: it reads .work/src/check.out)

Everything is generated from the repo, never edit the notes by hand:
  OUTDIR/Home.md               the tables, plain and as Dataview queries
  OUTDIR/Functions/NAME.md     one note per function of RRR's own C: address, status, rows,
                               module, the src/nearmiss.txt entry, the levers that name it
  OUTDIR/Levers/TITLE.md       one note per lever / dead end / probe trap of MATCHING.md and
                               GOTCHAS.md, with the functions it names
Only Home.md and the notes inside Functions/ and Levers/ are written or removed; anything else in
OUTDIR is left alone.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MARK = '> Generated by `reverse-engineering/tools/vault.py` from the repo. Do not edit: changes are overwritten.\n'


def read(p):
    return open(os.path.join(ROOT, p), encoding='utf-8').read()


def functions():
    """name -> dict, from check.out (status, size, address), nearmiss.txt, names, subsystems, src/"""
    fn = {}
    for l in read('.work/src/check.out').split('\n'):
        m = re.match(r'(\w+?)_\s+(\d+) bytes\s+(MATCH at|differs from) 0x0*([0-9a-f]+)', l)
        if m:
            fn[m.group(1)] = dict(size=int(m.group(2)), addr=int(m.group(4), 16),
                                  status='match' if m.group(3) == 'MATCH at' else 'near-miss',
                                  rows=0, history=[], note='', nm='')
    # nearmiss.txt: "70 -> 67 -> 6 0xADDR name  STATUS text" + indented continuation lines
    cur = None
    for l in read('src/nearmiss.txt').split('\n'):
        m = re.match(r'((?:\d+ ?-> ?|\d+-)*\d+) 0x([0-9a-f]+) (\w+)\s*(.*)', l)
        if m:
            name = m.group(3)
            cur = fn.setdefault(name, dict(size=0, addr=int(m.group(2), 16), status='asm', rows=0,
                                           history=[], note='', nm=''))
            cur['history'] = [int(x) for x in re.findall(r'\d+', m.group(1))]
            cur['note'] = m.group(4)
            s = re.match(r'(MATCH|SKIP|LAYOUT|ASM|OPEN)\b', m.group(4))
            cur['nm'] = s.group(1) if s else 'OPEN'
            if cur['status'] == 'near-miss':
                cur['rows'] = cur['history'][-1]
            if cur['nm'] == 'ASM':
                cur['status'] = 'asm'
        elif cur is not None and l.startswith('   '):
            cur['note'] += '\n' + l.strip()
        elif not l.strip() or l.startswith('#'):
            cur = None
    # the measured rows win over the hand-kept numbers
    r = subprocess.run([os.path.join(ROOT, 'reverse-engineering', 'tools', 'wc', 'nearmiss.sh')],
                       capture_output=True, text=True).stdout
    for l in r.split('\n'):
        m = re.match(r'(\d+) 0x[0-9a-f]+ (\w+)', l)
        if m and m.group(2) in fn:
            f = fn[m.group(2)]
            f['rows'] = int(m.group(1))
            if not f['history'] or f['history'][-1] != f['rows']:
                f['history'].append(f['rows'])
    for l in read('reverse-engineering/analysis/rrr_names.txt').split('\n'):
        m = re.match(r'0x([0-9a-f]+) (\w+)\s*(?:#\s*(.*))?', l)
        if m and m.group(2) in fn and int(m.group(1), 16) == fn[m.group(2)]['addr']:
            fn[m.group(2)]['evidence'] = m.group(3) or ''
    sub = None
    for l in read('reverse-engineering/analysis/rrr_subsystems.txt').split('\n'):
        if l.startswith('## '):
            sub = l[3:].strip()
        elif sub and not l.startswith('#'):
            for n in l.split():
                if n in fn:
                    fn[n]['subsystem'] = sub
    for f in sorted(os.listdir(os.path.join(ROOT, 'src'))):
        if f.endswith('.c'):
            s = read('src/' + f)
            for n in fn:
                if re.search(r'^[^\n;#/*]*\b%s\([^;{]*\)\s*\{' % re.escape(n), s, re.M):
                    fn[n].setdefault('module', 'src/' + f)
    return fn


def bullets(text):
    """top-level '- **Title** body' bullets, with their continuation lines"""
    out, cur = [], None
    for l in text.split('\n'):
        if l.startswith('- '):
            cur = [l[2:]]
            out.append(cur)
        elif cur is not None and (l.startswith('  ') or not l.strip()):
            cur.append(l.strip())
        else:
            cur = None
    return ['\n'.join(b).strip() for b in out]


def section(text, start, end):
    a = text.index(start) + len(start)
    b = text.index(end, a) if end else len(text)
    return text[a:b]


def levers():
    m, g = read('MATCHING.md'), read('GOTCHAS.md')
    src = [('lever', 'MATCHING.md', section(m, 'Levers seen so far', '\n## 6.')),
           ('lever', 'GOTCHAS.md', section(g, '### Levers that produced MATCHes on RRR', '\n### Probes')),
           ('probe-trap', 'GOTCHAS.md', section(g, '\n### Probes', '\n### Dead ends on RRR')),
           ('dead-end', 'GOTCHAS.md', section(g, '\n### Dead ends on RRR', '\n## ') if '\n## ' in
            g[g.index('### Dead ends on RRR'):] else section(g, '\n### Dead ends on RRR', None))]
    out, seen = [], set()
    for kind, where, text in src:
        for b in bullets(text):
            t = re.match(r'(?:\.\.\. )?\*\*(.+?)\*\*', b, re.S)
            if not t:
                continue
            title = re.sub(r'\s+', ' ', t.group(1)).strip(' .:')
            title = re.sub(r'^\.\.\. ', '', title)
            slug = title.replace('||', 'or').replace('->', 'to').replace('/', '-').replace('*', 'x')
            slug = re.sub(r'\s+', ' ', re.sub(r'[\\:?"<>|#^\[\]`]', '', slug))[:90].strip(' ,.')
            if slug.lower() in seen:
                slug += ' (%s)' % where[:-3]
            seen.add(slug.lower())
            out.append(dict(kind=kind, source=where, title=title, slug=slug, text=b))
    return out


def yaml(d):
    r = ['---']
    for k, v in d.items():
        if isinstance(v, list):
            r.append('%s: [%s]' % (k, ', '.join(str(x) for x in v)))
        elif isinstance(v, str):
            r.append('%s: "%s"' % (k, v.replace('\\', '\\\\').replace('"', '\\"')))
        else:
            r.append('%s: %s' % (k, v))
    return '\n'.join(r + ['---', ''])


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = os.path.abspath(sys.argv[1])
    fn, lv = functions(), levers()
    names = sorted(fn, key=len, reverse=True)
    pat = re.compile(r'\b(%s)\b' % '|'.join(map(re.escape, names)))
    for l in lv:
        l['fns'] = sorted(set(pat.findall(l['text'])))
    commit = subprocess.run(['git', '-C', ROOT, 'log', '-1', '--format=%h %ad', '--date=short'],
                            capture_output=True, text=True).stdout.strip()
    files = {}
    for n, f in fn.items():
        mine = [l for l in lv if n in l['fns']]
        fm = dict(address='0x%x' % f['addr'], status=f['status'], rows=f['rows'],
                  rows_history=f['history'], size=f['size'], module=f.get('module', ''),
                  subsystem=f.get('subsystem', 'unsorted'), nearmiss_status=f['nm'],
                  levers=len(mine), tags=['rrr/function', 'rrr/' + f['status']])
        b = [yaml(fm), MARK, '# %s' % n, '',
             '`0x%x` in RRR.EXE, %s, %s.' % (f['addr'], f.get('module', 'no C in src/'),
                                             {'match': 'byte-identical',
                                              'near-miss': '%d instruction rows from the game' % f['rows'],
                                              'asm': 'hand-written assembly, not compared'}[f['status']]), '']
        if f.get('evidence'):
            b += ['**Name evidence:** ' + f['evidence'], '']
        if len(f['history']) > 1:
            b += ['**Rows over time:** ' + ' → '.join(map(str, f['history'])), '']
        if f['note']:
            b += ['## Near-miss record (`src/nearmiss.txt`)', '', f['note'], '']
        if mine:
            b += ['## Levers and notes that name it', ''] + \
                 ['- [[%s]] (%s)' % (l['slug'], l['kind']) for l in mine] + ['']
        files['Functions/%s.md' % n] = '\n'.join(b)
    for l in lv:
        fm = dict(kind=l['kind'], source=l['source'], functions=len(l['fns']),
                  tags=['rrr/' + l['kind']])
        b = [yaml(fm), MARK, '# %s' % l['title'], '', l['text'], '']
        if l['fns']:
            b += ['## Functions it names', ''] + \
                 ['- [[%s]] (%s)' % (n, fn[n]['status'] if fn[n]['status'] != 'near-miss'
                                     else '%d rows' % fn[n]['rows']) for n in l['fns']] + ['']
        files['Levers/%s.md' % l['slug']] = '\n'.join(b)
    nm = sorted((n for n in fn if fn[n]['status'] == 'near-miss'), key=lambda n: (fn[n]['rows'], n))
    solved = sorted((n for n in fn if fn[n]['status'] == 'match' and fn[n]['nm'] == 'MATCH'),
                    key=lambda n: fn[n]['addr'])
    cnt = {s: sum(1 for f in fn.values() if f['status'] == s) for s in ('match', 'near-miss', 'asm')}
    h = [MARK, '# RRR matching decompilation', '',
         "RedCat's Razende Rekenrace, RRR.EXE's own C rebuilt with Watcom C. Repo state: `%s`." % commit, '',
         '%d functions: %d byte-identical, %d near misses, %d assembly.' %
         (len(fn), cnt['match'], cnt['near-miss'], cnt['asm']), '',
         '## Open near misses', '', '| Function | Rows | History | Module | Status |', '|---|---|---|---|---|']
    h += ['| [[%s]] | %d | %s | `%s` | %s |' % (n, fn[n]['rows'], (' → '.join(map(str, fn[n]['history'])) if len(fn[n]['history']) > 1 else ''),
                                              fn[n].get('module', ''), fn[n]['nm']) for n in nm]
    h += ['', '## Near misses that became byte-identical', '', '| Function | Address | History | Levers |',
          '|---|---|---|---|']
    h += ['| [[%s]] | `0x%x` | %s | %s |' % (n, fn[n]['addr'], (' → '.join(map(str, fn[n]['history'])) if len(fn[n]['history']) > 1 else ''),
                                           ', '.join('[[%s]]' % l['slug'] for l in lv if n in l['fns']))
          for n in solved]
    for kind, title in (('lever', 'Levers'), ('dead-end', 'Dead ends'), ('probe-trap', 'Probe traps')):
        h += ['', '## ' + title, '']
        h += ['- [[%s]]%s' % (l['slug'], ' — ' + ', '.join(l['fns']) if l['fns'] else '')
              for l in lv if l['kind'] == kind]
    h += ['', '## Live queries (needs the Dataview plugin)', '',
          '```dataview', 'TABLE rows, rows_history, module, nearmiss_status',
          'FROM #rrr/near-miss', 'SORT rows ASC', '```', '',
          '```dataview', 'TABLE kind, source, functions', 'FROM #rrr/lever OR #rrr/dead-end',
          'SORT functions DESC', '```', '',
          '```dataview', 'TABLE length(rows) AS functions, sum(rows.rows) AS "rows left"',
          'FROM #rrr/function', 'GROUP BY subsystem', '```', '']
    files['Home.md'] = '\n'.join(h)
    for d in ('Functions', 'Levers'):
        os.makedirs(os.path.join(out, d), exist_ok=True)
        for old in os.listdir(os.path.join(out, d)):
            p = os.path.join(out, d, old)
            if old.endswith('.md') and d + '/' + old not in files and MARK in open(p, encoding='utf-8').read():
                os.remove(p)
    for rel, text in files.items():
        open(os.path.join(out, rel), 'w', encoding='utf-8').write(text)
    print('%s: %d function notes, %d lever notes, Home.md' % (out, len(fn), len(lv)))


if __name__ == '__main__':
    main()
