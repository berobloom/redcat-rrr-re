"""Write port/src/anims_tab.c from RRR.EXE's static anim table (0x57798) and
port/src/menu_anims_tab.c from REKEN.EXE's (0x4660c, MENU.IMG images) and
port/src/rrrmenu_anims_tab.c from RRRMENU.EXE's (0x457bc, RRRANIM.IMG).

Each entry is {short frames, short flag, ptr} and each frame {short kind,
short image}; image i is RC.IMG entry i-1.  The table ends at -1.
Needs .work/le/rrr and .work/le/reken (see AGENTS.md setup).
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'reverse-engineering', 'tools'))
from lelib import Image  # noqa: E402

TABLES = [  # program, table, output file, C array, count macro
    ('rrr', 0x57798, 'anims_tab.c', 'rc_anims', 'RC_ANIM_COUNT'),
    ('reken', 0x4660c, 'menu_anims_tab.c', 'rc_menu_anims', 'RC_MENU_ANIM_COUNT'),
    ('rrrmenu', 0x457bc, 'rrrmenu_anims_tab.c', 'rc_rrrmenu_anims',
     'RC_RRRMENU_ANIM_COUNT'),
]


def write(prog, table, name, array, count):
    im = Image(prog)
    anims = []
    while True:
        n, extra, ptr = struct.unpack('<hhI', im.read(table + 8 * len(anims), 8))
        if n == -1 or extra == -1:
            break
        anims.append((extra, [struct.unpack('<hh', im.read(ptr + 4 * k, 4))
                              for k in range(n)]))
    out = ['/* Generated by port/tools/gen_anims.py from %s.EXE 0x%x. */'
           % (prog.upper(), table),
           '#include "anims.h"', '']
    for i, (_, frames) in enumerate(anims):
        out.append('static const rc_frame a%d[] = {' % i)
        for k in range(0, len(frames), 8):
            out.append('    ' + ' '.join('{%d,%d},' % f for f in frames[k:k + 8]))
        out.append('};')
    out.append('')
    out.append('const rc_anim %s[%s] = {' % (array, count))
    for i, (extra, frames) in enumerate(anims):
        out.append('    {%d, %d, a%d},' % (len(frames), extra, i))
    out.append('};')
    dst = os.path.join(HERE, '..', 'src', name)
    open(dst, 'w').write('\n'.join(out) + '\n')
    print('%d anims -> %s' % (len(anims), os.path.relpath(dst)))


def main():
    for t in TABLES:
        write(*t)


if __name__ == '__main__':
    main()
